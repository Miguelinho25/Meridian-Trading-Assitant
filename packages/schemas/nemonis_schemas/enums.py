"""Domain enumerations.

Reason codes are a stable public contract: they are written into immutable audit
records, so renaming one is a data migration, not a refactor (development.md).
"""

from __future__ import annotations

from enum import StrEnum


class Direction(StrEnum):
    LONG = "LONG"
    SHORT = "SHORT"


